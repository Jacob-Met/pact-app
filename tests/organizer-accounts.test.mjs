import test from "node:test";
import assert from "node:assert/strict";
import {mkdtemp,readFile,rm} from "node:fs/promises";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {randomBytes} from "node:crypto";
import {createSharedAgreementStore} from "../shared-agreements.mjs";
const key=()=>randomBytes(32).toString("base64url");
test("named organizers enroll separately, recover once, survive restart and revoke individually",async()=>{
 const dir=await mkdtemp(join(tmpdir(),"pact-accounts-")),path=join(dir,"shared.json"),code=key();let now=1000;
 const password="a violet river runs quietly",replacement="another patient mountain passage";
 try{
  let store=await createSharedAgreementStore({path,organizerCode:code,clock:()=>now});
  const root=await store.organizerLogin(code);
  const first=await store.organizerInvite(root.session,{name:"Morrow Sound"});
  assert.equal((await store.organizerInvitation(first.invitation)).name,"Morrow Sound");
  const alice=await store.organizerEnroll({invitation:first.invitation,username:"morrow",password});
  await assert.rejects(store.organizerEnroll({invitation:first.invitation,username:"again",password}),e=>e.status===401);
  assert.equal((await store.organizerRead(alice.session)).name,"Morrow Sound");
  await assert.rejects(store.organizerInvite(alice.session,{name:"Not allowed"}),e=>e.status===403);
  const second=await store.organizerInvite(root.session,{name:"Juniper Press"});
  const bob=await store.organizerEnroll({invitation:second.invitation,username:"juniper",password});
  const before=await readFile(path,"utf8");
  for(const secret of [password,alice.session,alice.recoveryCode,first.invitation,code])assert.equal(before.includes(secret),false);
  store=await createSharedAgreementStore({path,organizerCode:code,clock:()=>now});
  await store.organizerRead(alice.session);await store.organizerRead(bob.session);
  const fresh=await store.organizerAccountLogin({username:"MORROW",password});
  assert.equal(fresh.organizer.id,alice.organizer.id);
  await assert.rejects(store.organizerRecover({username:"juniper",recoveryCode:alice.recoveryCode,password:replacement}),e=>e.status===401);
  const recovered=await store.organizerRecover({username:"morrow",recoveryCode:alice.recoveryCode,password:replacement});
  assert.notEqual(recovered.recoveryCode,alice.recoveryCode);
  await assert.rejects(store.organizerRead(alice.session),e=>e.status===401);
  await assert.rejects(store.organizerRead(fresh.session),e=>e.status===401);
  await assert.rejects(store.organizerRecover({username:"morrow",recoveryCode:alice.recoveryCode,password:replacement}),e=>e.status===401);
  await assert.rejects(store.organizerAccountLogin({username:"morrow",password}),e=>e.status===401);
  await store.organizerRead(bob.session);await store.organizerRead(root.session);
  const current=await store.organizerAccountLogin({username:"morrow",password:replacement});
  await store.organizerRevoke(root.session,alice.organizer.id);
  await assert.rejects(store.organizerRead(current.session),e=>e.status===401);
  await assert.rejects(store.organizerAccountLogin({username:"morrow",password:replacement}),e=>e.status===401);
  await assert.rejects(store.organizerRecover({username:"morrow",recoveryCode:recovered.recoveryCode,password}),e=>e.status===401);
  await store.organizerRead(bob.session);
  const state=await store.organizerAccess(bob.session);assert.equal(state.accounts.length,0);assert.equal(state.organizer.admin,false);
  now+=8*60*60*1000;await assert.rejects(store.organizerRead(bob.session),e=>e.status===401);
 }finally{await rm(dir,{recursive:true,force:true});}
});
test("invitations, reset links, failed-attempt limits and password changes preserve authority boundaries",async()=>{
 const code=key();let now=1000;const store=await createSharedAgreementStore({organizerCode:code,clock:()=>now});
 const root=await store.organizerLogin(code),pass="a distant forest keeps its stories",next="several bright mornings by the sea";
 const unused=await store.organizerInvite(root.session,{name:"Cancelled invitation"});
 await store.organizerCancelInvite(root.session,unused.id);
 await assert.rejects(store.organizerInvitation(unused.invitation),e=>e.status===401);
 const invitation=await store.organizerInvite(root.session,{name:"Archive"});
 await assert.rejects(store.organizerEnroll({invitation:invitation.invitation,username:"archive",password:"short"}),e=>e.code==="ORGANIZER_PASSWORD");
 const a=await store.organizerEnroll({invitation:invitation.invitation,username:"archive",password:pass});
 for(let i=0;i<10;i++)await assert.rejects(store.organizerAccountLogin({username:"archive",password:"wrong"}),e=>[401,429].includes(e.status));
 await assert.rejects(store.organizerAccountLogin({username:"archive",password:pass}),e=>e.status===429);
 await store.organizerRead(root.session);
 const reset=await store.organizerInvite(root.session,{accountId:a.organizer.id});
 assert.equal((await store.organizerInvitation(reset.invitation)).username,"archive");
 const recovered=await store.organizerEnroll({invitation:reset.invitation,password:next});
 await assert.rejects(store.organizerRead(a.session),e=>e.status===401);
 await store.organizerAccountLogin({username:"archive",password:next});
 const changed=await store.organizerChange(recovered.session,{password:next,newPassword:pass,replaceRecovery:true});
 await assert.rejects(store.organizerRead(recovered.session),e=>e.status===401);
 await store.organizerRead(changed.session);
 assert.ok(changed.recoveryCode);
 const expiring=await store.organizerInvite(root.session,{name:"Expired"});
 now+=24*60*60*1000;await assert.rejects(store.organizerInvitation(expiring.invitation),e=>e.status===401);
});
